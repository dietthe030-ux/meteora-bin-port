import fs from "node:fs";
import path from "node:path";
import solc from "solc";

export function compileContracts() {
  const contractPath = path.join(process.cwd(), "contracts", "MeteoraLiquidityPort.sol");
  const source = fs.readFileSync(contractPath, "utf8");

  const input = {
    language: "Solidity",
    sources: {
      "MeteoraLiquidityPort.sol": {
        content: source,
      },
    },
    settings: {
      evmVersion: "paris",
      viaIR: true,
      optimizer: {
        enabled: true,
        runs: 1,
      },
      outputSelection: {
        "*": {
          "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object"],
        },
      },
    },
  };

  const output = JSON.parse(solc.compile(JSON.stringify(input)));

  if (output.errors) {
    const errors = output.errors.filter((e: { severity: string }) => e.severity === "error");
    for (const err of output.errors) {
      console.log(err.formattedMessage);
    }
    if (errors.length > 0) {
      throw new Error(`Compilation failed with ${errors.length} error(s).`);
    }
  }

  const compiled = output.contracts["MeteoraLiquidityPort.sol"]["MeteoraLiquidityPort"];
  const artifact = {
    contractName: "MeteoraLiquidityPort",
    abi: compiled.abi,
    bytecode: `0x${compiled.evm.bytecode.object}`,
    deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
  };

  const artifactsDir = path.join(process.cwd(), "artifacts");
  fs.mkdirSync(artifactsDir, { recursive: true });
  const artifactFile = path.join(artifactsDir, "MeteoraLiquidityPort.json");
  fs.writeFileSync(artifactFile, JSON.stringify(artifact, null, 2));

  const libDir = path.join(process.cwd(), "src", "lib");
  fs.mkdirSync(libDir, { recursive: true });
  const abiTsFile = path.join(libDir, "abi.ts");
  fs.writeFileSync(
    abiTsFile,
    `// Auto-generated by scripts/compile.ts — DO NOT EDIT MANUALLY\nexport const METEORA_LIQUIDITY_PORT_ABI = ${JSON.stringify(
      compiled.abi,
      null,
      2
    )} as const;\n`
  );

  console.log(`Compiled MeteoraLiquidityPort successfully -> ${artifactFile}`);
  return artifact;
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("compile.ts")) {
  compileContracts();
}
